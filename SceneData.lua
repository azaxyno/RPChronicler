-- A story's (or run's) theme key, or nil (the plain mist)
function ns.SceneTheme(st)
    if type(st) ~= "table" then return nil end
    -- the story's own header names the dungeon even when an older run was
    -- named after the city around it
    local info = ns.GetBookInfo and ns.GetBookInfo(st)
    if info and info.instance ~= "" and info.instance ~= st.instanceName then
        st = { kind = st.kind, instanceID = st.instanceID, instanceName = info.instance, zone = st.zone, title = st.title }
    end
    local key = ns.GetAdventureIcon and tostring(ns.GetAdventureIcon(st)):match("([%w_]+)%.png$")
    if key and ICON_THEME[key] and key ~= "dungeon" and key ~= "raid" then return ICON_THEME[key] end
    local hay = ((st.instanceName or "") .. " " .. (st.zone or "") .. " " .. (st.title or "")):lower()
    for _, e in ipairs(NAME_THEME) do
        if hay:find(e[1], 1, true) then return e[2] end
    end
    return key and ICON_THEME[key] or nil
end


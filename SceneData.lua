function ns.ZoneTerrain(text)
    text = tostring(text or ""):lower():gsub("|c%x%x%x%x%x%x%x%x", ""):gsub("|r", "")
    text = text:match("^%s*(.-)%s*$") or ""
    if text == "" then return nil end
    if ns.ZONE_TERRAIN[text] then return ns.ZONE_TERRAIN[text] end
    for part in text:gmatch("[^,%-]+") do
        local p = part:match("^%s*(.-)%s*$")
        if ns.ZONE_TERRAIN[p] then return ns.ZONE_TERRAIN[p] end
    end
    return nil
end
